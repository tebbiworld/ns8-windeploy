def parse_extension_names(value):
    """'[{CSE}{TOOL}...][...]' -> {CSE: set(TOOL, ...)} (upper case)."""
    result = {}
    value = (value or "").strip()
    if not value:
        return result
    if not re.fullmatch(r"(\[(\{[0-9A-Fa-f-]{36}\})+\])+", value):
        raise GenError(f"unexpected extension names format: {value!r}")
    for group in re.findall(r"\[([^\]]*)\]", value):
        guids = [g.upper() for g in GUID_RE.findall(group)]
        result.setdefault(guids[0], set()).update(guids[1:])
    return result


def format_extension_names(mapping):
    """Inverse of parse_extension_names: groups sorted by CSE GUID, tool
    GUIDs sorted inside a group - the order the Group Policy editor writes
    (reference GPO of the handover)."""
    out = []
    for cse in sorted(mapping):
        out.append("[" + cse + "".join(sorted(mapping[cse])) + "]")
    return "".join(out)


def add_scheduled_tasks_extension(value):
    """Return gPCMachineExtensionNames with the scheduled task preference
    registered. The editor lists every tool extension under the null GUID as
    well; keep that."""
    mapping = parse_extension_names(value)
    mapping.setdefault(CSE_SCHEDULED_TASKS, set()).add(TOOL_SCHEDULED_TASKS)
    mapping.setdefault(NULL_GUID, set()).add(TOOL_SCHEDULED_TASKS)
    return format_extension_names(mapping)


def bump_machine_version(version_number):
    """versionNumber: user version in the upper 16 bit, computer version in
    the lower 16 bit. Increment the computer part; it wraps to 1, not 0
    (0 means "never changed" to the clients)."""
    version_number = int(version_number)
    if not 0 <= version_number <= 0xFFFFFFFF:
        raise GenError(f"versionNumber out of range: {version_number}")
    user = version_number >> 16
    machine = version_number & 0xFFFF
    machine = machine + 1 if machine < 0xFFFF else 1
    return (user << 16) | machine


def build_gpt_ini(version_number, display_name=None):
    """GPT.INI content, byte-identical to the reference GPO (CRLF, file
    name GPT.INI in upper case)."""
    lines = ["[General]", f"Version={int(version_number)}"]
    if display_name:
        lines.append(f"displayName={display_name}")
    return "\r\n".join(lines) + "\r\n"
